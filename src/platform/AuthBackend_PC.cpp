bool PlatformAuth::httpsRequest(const HttpRequest &request, HttpResponse &response)
{
	response = HttpResponse();
	UrlParts url;
	if (!parseHttpsUrl(request.url, url) || !ensureCaBundle())
		return false;

	mbedtls_net_context serverFd;
	mbedtls_ssl_context ssl;
	mbedtls_ssl_config conf;
	mbedtls_ctr_drbg_context drbg;
	mbedtls_entropy_context entropy;
	mbedtls_net_init(&serverFd);
	mbedtls_ssl_init(&ssl);
	mbedtls_ssl_config_init(&conf);
	mbedtls_ctr_drbg_init(&drbg);
	mbedtls_entropy_init(&entropy);

	// RAII teardown for the whole TLS pile.
	struct Cleanup
	{
		mbedtls_net_context *fd;
		mbedtls_ssl_context *ssl;
		mbedtls_ssl_config *conf;
		mbedtls_ctr_drbg_context *drbg;
		mbedtls_entropy_context *entropy;
		~Cleanup()
		{
			mbedtls_net_free(fd);
			mbedtls_ssl_free(ssl);
			mbedtls_ssl_config_free(conf);
			mbedtls_ctr_drbg_free(drbg);
			mbedtls_entropy_free(entropy);
		}
	} cleanup{&serverFd, &ssl, &conf, &drbg, &entropy};

	const char *personalization = "opticraft-msauth";
	int rc = mbedtls_ctr_drbg_seed(&drbg, mbedtls_entropy_func, &entropy,
	                               reinterpret_cast<const unsigned char *>(personalization),
	                               std::strlen(personalization));
	if (rc != 0)
	{
		logTlsError("drbg seed failed", rc);
		return false;
	}
	if ((rc = mbedtls_ssl_config_defaults(&conf, MBEDTLS_SSL_IS_CLIENT,
	                                      MBEDTLS_SSL_TRANSPORT_STREAM,
	                                      MBEDTLS_SSL_PRESET_DEFAULT)) != 0)
	{
		logTlsError("ssl config failed", rc);
		return false;
	}
	// Mbed TLS 3.x returns void here (it was int in 2.x).
	mbedtls_ssl_conf_ca_chain(&conf, &caBundle, nullptr);
	mbedtls_ssl_conf_authmode(&conf, MBEDTLS_SSL_VERIFY_REQUIRED);
	mbedtls_ssl_conf_rng(&conf, mbedtls_ctr_drbg_random, &drbg);
	mbedtls_ssl_conf_read_timeout(&conf, kReadTimeoutMs);

	if ((rc = mbedtls_ssl_setup(&ssl, &conf)) != 0 ||
	    (rc = mbedtls_ssl_set_hostname(&ssl, url.host.c_str())) != 0)
	{
		logTlsError("ssl setup failed", rc);
		return false;
	}
	mbedtls_ssl_set_bio(&ssl, &serverFd, mbedtls_net_send, mbedtls_net_recv, mbedtls_net_recv_timeout);

	if ((rc = mbedtls_net_connect(&serverFd, url.host.c_str(), url.port.c_str(),
	                              MBEDTLS_NET_PROTO_TCP)) != 0)
	{
		logTlsError("connect failed", rc);
		return false;
	}
	while ((rc = mbedtls_ssl_handshake(&ssl)) != 0)
	{
		if (rc != MBEDTLS_ERR_SSL_WANT_READ && rc != MBEDTLS_ERR_SSL_WANT_WRITE)
		{
			logTlsError("handshake failed", rc);
			return false;
		}
	}

	// Request head + body.
	std::string head;
	head += request.method;
	head += ' ';
	head += url.path;
	head += " HTTP/1.1\r\n";
	head += "Host: " + url.host + "\r\n";
	head += std::string("User-Agent: ") + kUserAgent + "\r\n";
	head += "Connection: close\r\n";
	for (const auto &header : request.headers)
		head += header.first + ": " + header.second + "\r\n";
	if (request.method == "POST")
		head += "Content-Length: " + std::to_string(request.body.size()) + "\r\n";
	head += "\r\n";
	head += request.body;

	std::size_t sent = 0;
	while (sent < head.size())
	{
		rc = mbedtls_ssl_write(&ssl,
		                       reinterpret_cast<const unsigned char *>(head.data() + sent),
		                       head.size() - sent);
		if (rc == MBEDTLS_ERR_SSL_WANT_READ || rc == MBEDTLS_ERR_SSL_WANT_WRITE)
			continue;
		if (rc <= 0)
		{
			logTlsError("write failed", rc);
			return false;
		}
		sent += static_cast<std::size_t>(rc);
	}

	// Connection: close means EOF delimits the body; the read loop also
	// stops on read timeouts (server closed without close_notify) -- the
	// parser is content-length agnostic there, same as curl's behavior.
	std::string raw;
	std::vector<unsigned char> chunk(16 * 1024);
	for (;;)
	{
		rc = mbedtls_ssl_read(&ssl, chunk.data(), chunk.size());
		if (rc == 0 || rc == MBEDTLS_ERR_SSL_PEER_CLOSE_NOTIFY ||
		    rc == MBEDTLS_ERR_SSL_TIMEOUT || rc == MBEDTLS_ERR_NET_CONN_RESET)
			break;
		if (rc == MBEDTLS_ERR_SSL_WANT_READ || rc == MBEDTLS_ERR_SSL_WANT_WRITE)
			continue;
		if (rc < 0)
		{
			logTlsError("read failed", rc);
			return false;
		}
		if (raw.size() + static_cast<std::size_t>(rc) > kMaxResponseBytes)
		{
			MC_LOG_ERROR("auth", "pc: response over the size cap\n");
			return false;
		}
		raw.append(reinterpret_cast<const char *>(chunk.data()), static_cast<std::size_t>(rc));
	}

	return parseHttpResponse(raw, response.status, response.body);
}


constexpr std::size_t kMaxResponseBytes = 1024 * 1024;
constexpr uint32_t kReadTimeoutMs = 30000;
constexpr const char *kUserAgent = "OptiCraft-Heritage/PC";

struct UrlParts
{
	std::string host;
	std::string port;
	std::string path;
};

bool parseHttpsUrl(const std::string &url, UrlParts &out)
{
	const std::string scheme = "https://";
	if (url.compare(0, scheme.size(), scheme) != 0)
		return false;
	const std::size_t authorityStart = scheme.size();
	const std::size_t pathStart = url.find('/', authorityStart);
	const std::string authority = pathStart == std::string::npos
		? url.substr(authorityStart)
		: url.substr(authorityStart, pathStart - authorityStart);
	if (authority.empty() || authority.find('[') != std::string::npos)
		return false; // the auth endpoints are plain DNS names
	out.path = pathStart == std::string::npos ? "/" : url.substr(pathStart);
	out.port = "443";
	const std::size_t colon = authority.find(':');
	if (colon != std::string::npos)
	{
		out.host = authority.substr(0, colon);
		out.port = authority.substr(colon + 1);
	}
	else
	{
		out.host = authority;
	}
	return !out.host.empty();
}

std::once_flag caOnce;
bool caOk = false;
mbedtls_x509_crt caBundle;

bool ensureCaBundle()
{
	std::call_once(caOnce, []
	{
		mbedtls_x509_crt_init(&caBundle);
		const std::size_t length = std::strlen(opticraft_ca_bundle_pem);
		// >= 0: the count of *failed* certs is tolerated; only a fatal
		// negative return means the bundle did not load at all.
		caOk = mbedtls_x509_crt_parse(&caBundle,
		                              reinterpret_cast<const unsigned char *>(opticraft_ca_bundle_pem),
		                              length + 1) >= 0;
		if (!caOk)
		{
			mbedtls_x509_crt_free(&caBundle);
			MC_LOG_ERROR("auth", "pc: the embedded CA bundle could not be parsed\n");
		}
	});
	return caOk;
}

void logTlsError(const char *what, int code)
{
	char buffer[256] = {0};
	mbedtls_strerror(code, buffer, sizeof buffer);
	MC_LOG_ERROR("auth", "pc: %s: %s (-0x%04x)\n", what, buffer, -code);
}

bool containsCaseInsensitive(const std::string &text, const char *needle)
{
	const std::size_t needleLength = std::strlen(needle);
	if (text.size() < needleLength)
		return false;
	for (std::size_t i = 0; i + needleLength <= text.size(); i++)
	{
		std::size_t j = 0;
		while (j < needleLength)
		{
			const char a = text[i + j];
			const char b = needle[j];
			const char lowerA = a >= 'A' && a <= 'Z' ? static_cast<char>(a - 'A' + 'a') : a;
			const char lowerB = b >= 'A' && b <= 'Z' ? static_cast<char>(b - 'A' + 'b') : b;
			if (lowerA != lowerB)
				break;
			j++;
		}
		if (j == needleLength)
			return true;
	}
	return false;
}

// HTTP/1.1 response parsing: status line + headers + body, with both
// Content-Length and chunked transfer decoding. Deliberately minimal --
// the login endpoints speak well-formed HTTP with small bodies.
bool parseHttpResponse(const std::string &raw, int &status, std::string &body)
{
	const std::size_t headerEnd = raw.find("\r\n\r\n");
	if (headerEnd == std::string::npos || raw.compare(0, 5, "HTTP/") != 0)
		return false;
	const std::string head = raw.substr(0, headerEnd);
	std::string rest = raw.substr(headerEnd + 4);

	const std::size_t space = head.find(' ');
	if (space == std::string::npos || space + 3 >= head.size())
		return false;
	status = std::atoi(head.c_str() + space + 1);
	if (status < 100 || status > 599)
		return false;

	if (containsCaseInsensitive(head, "transfer-encoding:") &&
	    containsCaseInsensitive(head, "chunked"))
	{
		body.clear();
		std::size_t position = 0;
		for (;;)
		{
			const std::size_t lineEnd = rest.find("\r\n", position);
			if (lineEnd == std::string::npos)
				return false;
			const std::string sizeText = rest.substr(position, lineEnd - position);
			char *endPtr = nullptr;
			const unsigned long long chunkSize = std::strtoull(sizeText.c_str(), &endPtr, 16);
			if (endPtr == nullptr || endPtr == sizeText.c_str() || chunkSize == 0)
				return chunkSize == 0; // the zero chunk is the real terminator
			if (body.size() + chunkSize > kMaxResponseBytes)
				return false;
			const std::size_t chunkStart = lineEnd + 2;
			if (chunkStart + chunkSize + 2 > rest.size())
				return false;
			body.append(rest, chunkStart, chunkSize);
			position = chunkStart + chunkSize + 2; // skip chunk + trailing CRLF
		}
	}

	// Content-Length or connection-close delimited (read loop stops at EOF).
	body = std::move(rest);
	return true;
}

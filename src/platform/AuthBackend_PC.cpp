// AuthBackend_PC.cpp -- Microsoft/Mojang login transport for the desktop.
//
// Mbed TLS (external/mbedtls, Apache-2.0, pinned submodule -- see
// .gitmodules) speaking HTTP/1.1 over mbedtls_net sockets: no dependency on
// whatever TLS the host happens to ship, and the same library family the
// 3DS portlibs' curl is built on. The Mozilla CA bundle
// (resources/cacert.pem, MPL-2.0) is compiled into the binary
// (generated/PcCaBundle.cpp from resources/PcCaBundle.cpp.in) and both the
// chain and the host name are verified -- this channel carries account
// tokens.
//
// The desktop target always wires the transport (Mbed TLS + the embedded CA
// bundle), so this file always builds the real channel; the login UI itself
// stays hidden until a client id is configured (see OPTICRAFT_MSA_CLIENT_ID).

